"""Crop the six approved Lucy portraits and build the existing data-image choices."""
import base64
import json
from pathlib import Path
from PIL import Image, ImageOps

root = Path(__file__).resolve().parents[1]
source = root / '.job/lucy-approved'
out = root / 'accounts/lucy'
out.mkdir(exist_ok=True)
choices = [
    ('01-garden-b-1.jpg', 'garden', 'Lucy in the garden', (425, 0, 785, 360)),
    ('03-nap-1.jpg', 'nap', 'Sleepy Lucy', (185, 255, 685, 755)),
    ('07-seedream-letterpost-mailbox.png', 'mailbox', 'Lucy by the mailbox', (785, 10, 1575, 800)),
    ('09-seedream-celebrate-leap.png', 'celebrate', 'Celebrating Lucy', (625, 0, 1465, 840)),
    ('10-seedream-classroom-wave.png', 'wave', 'Waving Lucy', (585, 35, 1485, 935)),
    ('11-seedream-headtilt-nudge.png', 'headtilt', 'Curious Lucy', (640, 5, 1520, 885)),
]
records = []
for name, key, label, box in choices:
    image = ImageOps.exif_transpose(Image.open(source / name)).convert('RGB')
    # Clamp the sleeping crop to the source height without adding a black edge.
    left, top, right, bottom = (tuple(round(v * image.width / 2048) for v in box)
                                if name.endswith(".png") else box)
    if bottom > image.height:
        top -= bottom - image.height
        bottom = image.height
    image = image.crop((left, top, right, bottom)).resize((192, 192), Image.Resampling.LANCZOS)
    target = out / (key + '.jpg')
    image.save(target, quality=85, optimize=True)
    data = 'data:image/jpeg;base64,' + base64.b64encode(target.read_bytes()).decode()
    records.append({'key': key, 'label': label, 'src': 'lucy/' + target.name, 'value': data})
    print(f'{target.relative_to(root)}: {target.stat().st_size} bytes')
(root / 'accounts/lucy-avatars.js').write_text('// Generated by scripts/build-lucy-avatars.py from approved sources.\nwindow.LUCY_AVATARS = ' + json.dumps(records, separators=(',', ':')) + ';\n')
